"""Load flash algorithm from manifest JSON + binary blob.

Uses importlib_resources for wheel/egg-safe file access.
Manifest JSON is generated by the flashloader build system (gen_manifest.py).
"""

import json
import struct
from typing import Dict, List

import importlib_resources

_PKG = 'pyocd.target.builtin.hpmicro'

# Map manifest symbol names to pyOCD algo dict keys.
# Both pyOCD format (flash_*) and FLM format (Init/EraseSector/*) are covered.
_SYMBOL_MAP = {
    # pyOCD format symbols
    'flash_init': 'pc_init',
    'flash_erase': 'pc_erase_sector',
    'flash_program': 'pc_program_page',
    'flash_read': 'pc_read',
    'flash_erase_chip': 'pc_eraseAll',
    'flash_deinit': 'pc_unInit',
    'flash_get_info': 'pc_get_info',
    # FLM format symbols
    'Init': 'pc_init',
    'UnInit': 'pc_unInit',
    'EraseSector': 'pc_erase_sector',
    'ProgramPage': 'pc_program_page',
    'EraseChip': 'pc_eraseAll',
}


def _load_blob_words(filename: str) -> List[int]:
    """Read binary blob from package, return as list of 32-bit LE words."""
    ref = importlib_resources.files(_PKG).joinpath(filename)
    data = ref.read_bytes()
    if len(data) % 4 != 0:
        raise ValueError(f"Blob size {len(data)} not word-aligned")
    return list(struct.unpack(f'<{len(data) // 4}I', data))


def _load_manifest(filename: str) -> Dict:
    """Read manifest JSON from package."""
    ref = importlib_resources.files(_PKG).joinpath(filename)
    return json.loads(ref.read_text(encoding='utf-8'))


def load_flash_algo(manifest_file: str, blob_file: str) -> Dict:
    """Load flash algo dict from manifest JSON + binary blob.

    Args:
        manifest_file: Filename of manifest JSON in the hpmicro package.
        blob_file: Filename of binary blob (.bin) in the hpmicro package.

    Returns:
        Algo dict with instructions, pc_* offsets, bss_size, bss_layout,
        p_filesz, p_memsz.
    """
    manifest = _load_manifest(manifest_file)
    instructions = _load_blob_words(blob_file)

    algo: Dict = {'instructions': instructions}

    # Map symbol offsets (first match wins, pyOCD names take priority)
    for sym_name, algo_key in _SYMBOL_MAP.items():
        offset = manifest.get('symbols', {}).get(sym_name)
        if offset is not None and algo_key not in algo:
            algo[algo_key] = offset

    # For formats where p_filesz == p_memsz (e.g. FLM), BSS is embedded
    # in the blob and the adapter should not zero-init extra space.
    p_filesz = manifest.get('p_filesz', 0)
    p_memsz = manifest.get('p_memsz', 0)
    manifest_bss = manifest.get('bss_total_size', 0)

    if p_filesz == p_memsz and manifest_bss > 0:
        # BSS already in blob (FLM-style) — adapter bss_size = 0
        algo['bss_size'] = 0
    else:
        algo['bss_size'] = manifest_bss

    algo['p_filesz'] = p_filesz
    algo['p_memsz'] = p_memsz

    # BSS variable layout (offsets from blob start)
    bss_raw = manifest.get('bss', {})
    algo['bss_layout'] = {name: entry['offset'] for name, entry in bss_raw.items()}
    algo['bss_sizes'] = {name: entry.get('size', 4) for name, entry in bss_raw.items()}

    # Global pointer and stack top from ELF linker symbols.
    # Required for blobs that use GP-relative addressing (ROM API calls).
    if 'static_base' in manifest:
        algo['static_base'] = manifest['static_base']
    if 'stack_top' in manifest:
        algo['stack_top'] = manifest['stack_top']

    return algo
